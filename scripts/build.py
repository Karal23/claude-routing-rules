#!/usr/bin/env python3
"""Build client rule sets from the checked-in source snapshots."""

import argparse
import ipaddress
import json
from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parents[1]


def geosite(name):
    result = {"domain": set(), "domain_suffix": set()}
    for raw in (ROOT / "sources/geosite" / name).read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        # Attributes such as @cn do not restrict the requested whole category.
        value = line.split()[0]
        if value.startswith("include:"):
            for field, values in geosite(value.split(":", 1)[1]).items():
                result[field].update(values)
        elif value.startswith("full:"):
            result["domain"].add(value.split(":", 1)[1])
        elif ":" not in value:
            result["domain_suffix"].add(value)
        else:
            raise ValueError(f"Unsupported geosite entry in {name}: {value}")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sing-box", default="sing-box", help="sing-box executable")
    args = parser.parse_args()
    source = json.loads((ROOT / "sources/net-coffee.json").read_text())
    domains = {field: set(source[field]) for field in
               ("domain", "domain_suffix", "domain_keyword")}
    for category in ("anthropic", "category-ntp"):
        for field, values in geosite(category).items():
            domains[field].update(values)
    domain_rule = {field: sorted(values) for field, values in domains.items()}

    asn = json.loads((ROOT / "sources/as399358.json").read_text())
    networks = [ipaddress.ip_network(value) for value in
                source["ip_cidr"] + asn["prefixes"]]
    cidrs = [str(network) for version in (4, 6) for network in
             ipaddress.collapse_addresses(n for n in networks if n.version == version)]
    # Separate headless rules keep domain and destination-IP matching independent.
    rule_set = {"version": 2, "rules": [domain_rule, {"ip_cidr": cidrs}]}
    sing_dir = ROOT / "sing-box"
    sing_dir.mkdir(exist_ok=True)
    source_path = sing_dir / "claude.json"
    source_path.write_text(json.dumps(rule_set, ensure_ascii=False, indent=2) + "\n")
    subprocess.run([args.sing_box, "rule-set", "compile", "--output",
                    str(sing_dir / "claude.srs"), str(source_path)], check=True)

    domain_lines = []
    for field, kind in (("domain", "DOMAIN"), ("domain_suffix", "DOMAIN-SUFFIX"),
                        ("domain_keyword", "DOMAIN-KEYWORD")):
        domain_lines.extend(f"{kind},{value}" for value in domain_rule[field])
    ip_lines = []
    for cidr in cidrs:
        kind = "IP-CIDR" if ipaddress.ip_network(cidr).version == 4 else "IP-CIDR6"
        ip_lines.append(f"{kind},{cidr},no-resolve")

    mihomo_dir = ROOT / "mihomo"
    mihomo_dir.mkdir(exist_ok=True)
    payload = [f"  - {json.dumps(line)}" for line in domain_lines + ip_lines]
    (mihomo_dir / "claude.yaml").write_text("payload:\n" + "\n".join(payload) + "\n")

    lines = [
        "# Claude complete rules: core, CDN, auth, telemetry, widgets, NTP, IP/ASN",
        "# Source: https://ip.net.coffee/claude/site.html",
        "# Repository: https://github.com/Karal23/claude-routing-rules",
        "# Generated by scripts/build.py; set the policy in [Remote Rule].",
        "# NTP category affects all matching device traffic, not only Claude.",
        "",
    ]
    lines.extend(domain_lines + [""] + ip_lines)
    lines.extend(f"IP-ASN,{asn_id},no-resolve" for asn_id in source["ip_asn"])
    (ROOT / "loon").mkdir(exist_ok=True)
    (ROOT / "loon/claude.list").write_text("\n".join(lines) + "\n")
    print(f"Built {sum(map(len, domain_rule.values()))} domain/keyword entries, "
          f"{len(cidrs)} CIDRs, and {len(source['ip_asn'])} native Loon ASN rule.")


if __name__ == "__main__":
    main()
